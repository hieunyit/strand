// g2MySQLOp: thao tác trên source MySQL — insert AUTO_INCREMENT (một row / nhiều row), update và
// xóa ngẫu nhiên gần đỉnh, thỉnh thoảng xóa row có id lớn nhất.
func g2MySQLOp(db *sql.DB, hi map[string]*atomic.Int64) func(r *rand.Rand) error {
	return func(r *rand.Rand) error {
		tb := g2MySQLTables[r.Intn(len(g2MySQLTables))]
		near := func() int64 {
			h := hi[tb].Load()
			if h < 2 {
				return 1
			}
			return h - r.Int63n(min64(h, 400))
		}
		switch k := r.Intn(100); {
		case k < 45:
			res, err := db.Exec("INSERT INTO "+tb+" (n, note) VALUES (?, 'src')", r.Intn(1000))
			if err != nil {
				return err
			}
			if id, err := res.LastInsertId(); err == nil {
				maxStore(hi[tb], id)
			}
			return nil
		case k < 55:
			vals := strings.TrimSuffix(strings.Repeat("(?, 'batch'),", 25), ",")
			args := make([]any, 25)
			for i := range args {
				args[i] = r.Intn(1000)
			}
			res, err := db.Exec("INSERT INTO "+tb+" (n, note) VALUES "+vals, args...)
			if err != nil {
				return err
			}
			if id, err := res.LastInsertId(); err == nil {
				maxStore(hi[tb], id+24)
			}
			return nil
		case k < 85:
			_, err := db.Exec("UPDATE "+tb+" SET n = n + 1, note = 'upd' WHERE id = ?", near())
			return err
		case k < 97:
			_, err := db.Exec("DELETE FROM "+tb+" WHERE id = ?", near())
			return err
		default:
			_, err := db.Exec("DELETE FROM " + tb + " ORDER BY id DESC LIMIT 1")
			return err
		}
	}
}

func min64(a, b int64) int64 {
	if a < b {
		return a
	}
	return b
}

func maxStore(a *atomic.Int64, v int64) {
	for {
		cur := a.Load()
		if v <= cur || a.CompareAndSwap(cur, v) {
			return
		}
	}
}

// setupG2MySQLPG dựng MySQL→PG: preload 1000 row mỗi bảng ở source (đi qua snapshot logic), target
// có identity CACHE identCache và role ứng dụng; trả kèm map id lớn nhất từng bảng cho bộ sinh tải.
func setupG2MySQLPG(t *testing.T, identCache int) (*mysqlNode, *pgNode, map[string]*atomic.Int64) {
	t.Helper()
	src := startMySQL(t, mysqlImage("source"), "src", 1, nil)
	dst := startPG(t, "pgdst")
	src.exec(t, g2MySQLSourceSQL...)
	dst.exec(t, g2MySQLTargetSQL(identCache)...)
	dst.exec(t, g2AppRoleSQL("shop")...)
	hi := map[string]*atomic.Int64{}
	for _, tb := range g2MySQLTables {
		src.exec(t, "INSERT INTO "+tb+` (n, note) WITH RECURSIVE g(x) AS (SELECT 1 UNION ALL SELECT x + 1 FROM g WHERE x < 1000)
			SELECT x, CONCAT('p', x) FROM g`)
		var mx int64
		if err := src.DB.QueryRow("SELECT COALESCE(MAX(id), 0) FROM " + tb).Scan(&mx); err != nil {
			t.Fatal(err)
		}
		hi[tb] = &atomic.Int64{}
		hi[tb].Store(mx)
	}
	return src, dst, hi
}

// compareG2MySQLPG so từng row (id, n, note) giữa source MySQL và target PG.
func compareG2MySQLPG(t *testing.T, src *mysqlNode, dst *pgNode) {
	t.Helper()
	total := 0
	var bad []string
	for _, tb := range g2MySQLTables {
		q := "SELECT id, n, note FROM " + tb
		s, d := dumpCanon(t, src.DB, q, -1), dumpCanon(t, dst.DB, q, -1)
		total += len(s)
		for k, sv := range s {
			if dv, ok := d[k]; !ok {
				bad = append(bad, fmt.Sprintf("%s id=%s missing on target", tb, k))
			} else if strings.Join(sv, "|") != strings.Join(dv, "|") {
				bad = append(bad, fmt.Sprintf("%s id=%s differs: src %v dst %v", tb, k, sv, dv))
			}
		}
		for k := range d {
			if _, ok := s[k]; !ok {
				bad = append(bad, fmt.Sprintf("%s id=%s extra on target", tb, k))
			}
		}
	}
	if len(bad) > 0 {
		if len(bad) > 15 {
			bad = bad[:15]
		}
		t.Fatalf("final state mismatch:\n%s", strings.Join(bad, "\n"))
	}
	t.Logf("final state: %d rows identical", total)
}

