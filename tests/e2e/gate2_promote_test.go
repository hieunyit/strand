// Gate 2 (G2-4): PG→PG dưới tải ghi (identity ALWAYS CACHE 20, identity BY DEFAULT, sequence độc
// lập CACHE 50; nhiều session nên cache của từng session để lại khoảng trống) → sync tới khi theo
// kịp → dừng tải → `strand promote` (fence source, giữ read-only, apply nốt, setval, mở ghi) → ứng
// dụng insert ngay trên target bằng giá trị mặc định: 0 lỗi trùng khóa, id mới > mọi id đã
// replicate, sequence độc lập > last_value của source. Margin để nhỏ (--peak-rate 1
// --sync-interval 1 → 2·cache·|inc| + 2) để test nhạy với max(cột)/last_value đọc sai.
func TestG2_E2E_PromoteNoDuplicateKeyPGToPG(t *testing.T) {
	seed := seedFromEnv(t)
	slot, pub := "strand_g2_promote", "strand_g2_pub"
	src, dst, lsn := setupG2PGPair(t, slot, pub, 20, 50)

	wl := startG2Load(seed, 6, g2PGOp(src.DB))
	time.Sleep(2 * time.Second) // có tải trước khi Strand bắt đầu: phần đầu stream là backlog

	cfg := strandCfg{Name: "e2e-g2-promote-pg", SourceKind: "postgres", TargetKind: "postgres",
		SourceDSN: src.DSN, TargetDSN: dst.DSN,
		SourceExtra: fmt.Sprintf(", slot: %s, publication: %s, sequence_sync_interval: 1s", slot, pub),
		Include:     []string{"app.*"}, Dir: testDir(t), Bootstrap: "start_at"}
	p := startStrand(t, cfg.write(t), "--start-at", lsn)
	time.Sleep(time.Duration(envInt("STRAND_E2E_PG_LOAD_SECONDS", 20)) * time.Second)
	wl.Stop()
	t.Logf("source load: %s", wl.summary())
	if wl.ops.Load() < 200 {
		t.Fatalf("source load too small to be meaningful: %s", wl.summary())
	}
	waitPGCaughtUp(t, src, dst, &cfg, p, 5*time.Minute)

	requireSeqBehind(t, dst, "app.g_always", "app.g_always_id_seq")
	requireSeqBehind(t, dst, "app.g_bydefault", "app.g_bydefault_id_seq")
	requireSeqBehind(t, dst, "app.g_indep", "app.ext_seq")
	srcExt, _ := pgSeqState(t, src.DB, "app.ext_seq")

	appDSN := pgDSNAs(t, dst.DSN, "app_rw", "app")
	start := time.Now()
	out, code := runStrandCLI(t, 5*time.Minute, "promote",
		"--target", dst.DSN, "--fence", src.DSN, "--pipeline", cfg.Name,
		"--app-role", "app_rw", "--schemas", "app",
		"--peak-rate", "1", "--sync-interval", "1", "--catchup-timeout", "2m")
	if code != 0 {
		var sl string
		_ = src.DB.QueryRow("SELECT pg_current_wal_lsn()::text").Scan(&sl)
		t.Fatalf("promote: exit %d (source current WAL %s)\n%s\nstrand:\n%s", code, sl, out, p.tail())
	}
	t.Logf("promote finished in %s", time.Since(start).Round(time.Millisecond))

	// Ứng dụng ghi ngay khi promote trả về.
	floor, before := pgFloorsAndCounts(t, dst, pgAppStmts)
	if srcExt > floor["app.g_indep"] {
		floor["app.g_indep"] = srcExt
	}
	res := g2AppBurst(t, appDSN, pgAppStmts, envInt("STRAND_E2E_G2_APP_ROWS", 500), 8)
	checkBurst(t, dst, res, floor, before, envInt("STRAND_E2E_G2_APP_ROWS", 500))

	// Source cũ bị fence: không ghi được nữa.
	if _, err := src.DB.Exec("INSERT INTO app.marker VALUES (-1, 'after-fence')"); err == nil {
		t.Fatalf("old source still accepts writes after promote (not fenced)")
	} else {
		t.Logf("old source fenced: %v", err)
	}
	if st := loadPromoteRow(t, dst, cfg.Name); st.State != "promoted" {
		t.Fatalf("promote state %q, want promoted (steps %v)", st.State, st.Steps)
	}
	if code := p.stop(t); code != 0 {
		t.Errorf("strand exit %d after promote\n%s", code, p.tail())
	}
	// Dữ liệu replicate đủ: bỏ row ứng dụng ghi sau promote rồi so từng row với source.
	for _, s := range pgAppStmts {
		dst.exec(t, "DELETE FROM "+s.table+" WHERE note = 'app'")
	}
	comparePG(t, src, dst, g2PGTables...)
}

