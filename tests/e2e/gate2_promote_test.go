var suggestRe = regexp.MustCompile(`(?m)^\s*- (\S+): gợi ý (-?\d+)`)

// parseSuggestions đọc các dòng "  - <sequence>: gợi ý <N>" mà promote in khi dừng hỏi.
func parseSuggestions(out string) map[string]int64 {
	m := map[string]int64{}
	for _, g := range suggestRe.FindAllStringSubmatch(out, -1) {
		v, err := strconv.ParseInt(g[2], 10, 64)
		if err == nil {
			m[g[1]] = v
		}
	}
	return m
}

func requireContains(t *testing.T, what, out string, subs ...string) {
	t.Helper()
	for _, s := range subs {
		if !strings.Contains(out, s) {
			t.Fatalf("%s: output does not contain %q:\n%s", what, s, out)
		}
	}
}

// Gate 2 (G2-10), source PG: sequence độc lập app.ext_seq CACHE 1000 (và identity CACHE 1000), nhiều
// session ở source nên last_value của source vượt xa max(id) đã replicate. Strand sync đồng bộ
// last_value mỗi 1 s vào _strand_promote. Source bị cắt (docker pause) rồi promote:
//  1. lần 1: không fence được → exit 10 (promote_needs_decision), in tóm tắt dữ liệu sẽ mất, cách
//     xác nhận (--source-fenced-externally) và giá trị gợi ý cho app.ext_seq = lần sync cuối +
//     margin, margin = 2·1000·1 + 2·r_peak·Δt_sync (= 2200 với --peak-rate 100 --sync-interval 1);
//     target không bị đụng (sequence giữ nguyên, ứng dụng chưa ghi được);
//  2. lần 2 (--source-fenced-externally): fence/giữ read-only/apply nốt qua, nhưng sequence độc lập
//     không đọc được từ source → vẫn exit 10, chưa setval, chưa mở ghi;
//  3. lần 3 (--override-sequences = giá trị gợi ý): exit 0; ứng dụng insert ngay → 0 trùng khóa,
//     id của bảng dùng ext_seq > last_value thật của source (kể cả phần cache các session đã giữ).
func TestG2_E2E_PromoteSourceUnreachableCache1000PG(t *testing.T) {
	seed := seedFromEnv(t)
	slot, pub := "strand_g2_unreach", "strand_g2_pub"
	src, dst, lsn := setupG2PGPair(t, slot, pub, 1000, 1000)

	cfg := strandCfg{Name: "e2e-g2-unreach-pg", SourceKind: "postgres", TargetKind: "postgres",
		SourceDSN: src.DSN, TargetDSN: dst.DSN,
		SourceExtra: fmt.Sprintf(", slot: %s, publication: %s, sequence_sync_interval: 1s", slot, pub),
		Include:     []string{"app.*"}, Dir: testDir(t), Bootstrap: "start_at"}
	p := startStrand(t, cfg.write(t), "--start-at", lsn)
	wl := startG2Load(seed, 6, g2PGOp(src.DB))
	time.Sleep(time.Duration(envInt("STRAND_E2E_PG_LOAD_SECONDS", 20)) * time.Second)
	wl.Stop()
	t.Logf("source load: %s", wl.summary())
	waitPGCaughtUp(t, src, dst, &cfg, p, 5*time.Minute)

	srcExt, _ := pgSeqState(t, src.DB, "app.ext_seq")
	maxIndep := pgMaxID(t, src.DB, "app.g_indep")
	t.Logf("source app.ext_seq last_value %d (CACHE 1000, many sessions), max(app.g_indep.id) %d", srcExt, maxIndep)
	if srcExt <= maxIndep {
		t.Fatalf("precondition: source sequence cache should put last_value (%d) above max(id) (%d)", srcExt, maxIndep)
	}
	// Chờ sync định kỳ ghi giá trị cuối cùng của source vào _strand_promote.
	deadline := time.Now().Add(time.Minute)
	for syncedValue(dst, cfg.Name, "app.ext_seq") < srcExt {
		if time.Now().After(deadline) {
			t.Fatalf("periodic sequence sync did not reach source last_value %d (synced %d)\n%s",
				srcExt, syncedValue(dst, cfg.Name, "app.ext_seq"), p.tail())
		}
		time.Sleep(300 * time.Millisecond)
	}
	synced := syncedValue(dst, cfg.Name, "app.ext_seq")
	if code := p.stop(t); code != 0 {
		t.Fatalf("strand exit %d\n%s", code, p.tail())
	}
	tgtExt, tgtExtCalled := pgSeqState(t, dst.DB, "app.ext_seq")
	tgtAlways, _ := pgSeqState(t, dst.DB, "app.g_always_id_seq")

	pauseContainer(t, src.c)
	fence := withParam(src.DSN, "connect_timeout=3")
	appDSN := pgDSNAs(t, dst.DSN, "app_rw", "app")
	base := []string{"promote", "--target", dst.DSN, "--fence", fence, "--pipeline", cfg.Name,
		"--app-role", "app_rw", "--schemas", "app", "--peak-rate", "100", "--sync-interval", "1"}
	const margin = 2*1000*1 + 2*100*1

	// Lần 1: không fence được → dừng hỏi.
	out, code := runStrandCLI(t, 3*time.Minute, base...)
	if code != 10 {
		t.Fatalf("promote with unreachable source: exit %d, want 10\n%s", code, out)
	}
	requireContains(t, "promote #1", out, "promote_needs_decision", "PROMOTE NEEDS OPERATOR DECISION",
		"--source-fenced-externally", "Dữ liệu sẽ mất nếu tiếp tục", "target applied up to", "--override-sequences")
	sug := parseSuggestions(out)
	got, ok := sug["app.ext_seq"]
	if !ok {
		t.Fatalf("promote #1 does not name the independent sequence app.ext_seq with a suggested value:\n%s", out)
	}
	if got != synced+margin {
		t.Fatalf("suggested value for app.ext_seq = %d, want last synced %d + margin %d = %d", got, synced, margin, synced+margin)
	}
	if got <= srcExt {
		t.Fatalf("suggested value %d is not above the source last_value %d", got, srcExt)
	}
	for name := range sug {
		if name != "app.ext_seq" {
			t.Fatalf("promote #1 asks about %s, which is attached to a column (max(col) + margin, no decision needed):\n%s", name, out)
		}
	}
	st := loadPromoteRow(t, dst, cfg.Name)
	if st.State != "awaiting_operator" || st.has("fence_source") || st.has("setval") || st.Suggested["app.ext_seq"] != got {
		t.Fatalf("promote #1 saved state %+v, want awaiting_operator without fence_source/setval and suggestion %d", st, got)
	}
	if v, c := pgSeqState(t, dst.DB, "app.ext_seq"); v != tgtExt || c != tgtExtCalled {
		t.Fatalf("promote #1 changed target app.ext_seq (%d,%v → %d,%v) before a decision", tgtExt, tgtExtCalled, v, c)
	}
	if v, _ := pgSeqState(t, dst.DB, "app.g_always_id_seq"); v != tgtAlways {
		t.Fatalf("promote #1 changed target identity sequence (%d → %d) before a decision", tgtAlways, v)
	}
	requireAppCannotWrite(t, appDSN, pgAppStmts[2].insert)
	t.Logf("promote #1 stopped and asked: app.ext_seq suggestion %d (synced %d + margin %d; source last_value %d)", got, synced, margin, srcExt)

	// Lần 2: xác nhận source đã cô lập; sequence độc lập vẫn không đọc được → vẫn hỏi.
	out, code = runStrandCLI(t, 3*time.Minute, append(base, "--source-fenced-externally")...)
	if code != 10 {
		t.Fatalf("promote --source-fenced-externally without override: exit %d, want 10\n%s", code, out)
	}
	requireContains(t, "promote #2", out, "promote_needs_decision", "independent sequences could not be read", "--override-sequences")
	if v := parseSuggestions(out)["app.ext_seq"]; v != got {
		t.Fatalf("promote #2 suggestion for app.ext_seq = %d, want %d (same as #1)\n%s", v, got, out)
	}
	st = loadPromoteRow(t, dst, cfg.Name)
	if st.State != "awaiting_operator" || !st.has("fence_source") || !st.has("hold_readonly") || st.has("setval") || st.has("open_writes") {
		t.Fatalf("promote #2 saved state %+v, want awaiting_operator after fence/hold, before setval/open_writes", st)
	}
	if v, c := pgSeqState(t, dst.DB, "app.ext_seq"); v != tgtExt || c != tgtExtCalled {
		t.Fatalf("promote #2 changed target app.ext_seq (%d,%v → %d,%v) before a decision", tgtExt, tgtExtCalled, v, c)
	}
	requireAppCannotWrite(t, appDSN, pgAppStmts[2].insert)

	// Lần 3: người vận hành duyệt giá trị gợi ý.
	override := fmt.Sprintf(`{"app.ext_seq": %d}`, got)
	out, code = runStrandCLI(t, 3*time.Minute, append(base, "--source-fenced-externally", "--override-sequences", override)...)
	if code != 0 {
		t.Fatalf("promote with operator decision: exit %d, want 0\n%s", code, out)
	}
	if st := loadPromoteRow(t, dst, cfg.Name); st.State != "promoted" {
		t.Fatalf("promote #3 state %q, want promoted (steps %v)", st.State, st.Steps)
	}
	floor, before := pgFloorsAndCounts(t, dst, pgAppStmts)
	if srcExt > floor["app.g_indep"] {
		floor["app.g_indep"] = srcExt
	}
	rows := envInt("STRAND_E2E_G2_APP_ROWS", 500)
	res := g2AppBurst(t, appDSN, pgAppStmts, rows, 8)
	checkBurst(t, dst, res, floor, before, rows)
}

