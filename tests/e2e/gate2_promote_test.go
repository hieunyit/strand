type g2AppStmt struct {
	table  string
	insert string // INSERT … RETURNING id, tham số $1 = n
}

type g2BurstResult struct {
	ids   map[string][]int64
	dups  int
	other []string
}

// g2AppBurst: ứng dụng (role app_rw, kết nối mới) chèn perTable row vào mỗi bảng bằng giá trị mặc định,
// workers kết nối song song. Lỗi 23505 (unique_violation) đếm riêng; mọi lỗi khác ghi lại nguyên văn.
func g2AppBurst(t *testing.T, appDSN string, stmts []g2AppStmt, perTable, workers int) g2BurstResult {
	t.Helper()
	db, err := sql.Open("pgx", appDSN)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	db.SetMaxOpenConns(workers)
	jobs := make(chan int, len(stmts)*perTable)
	for i := 0; i < perTable; i++ {
		for j := range stmts {
			jobs <- j
		}
	}
	close(jobs)
	res := g2BurstResult{ids: map[string][]int64{}}
	var mu sync.Mutex
	var wg sync.WaitGroup
	for w := 0; w < workers; w++ {
		wg.Add(1)
		go func(w int) {
			defer wg.Done()
			for j := range jobs {
				var id int64
				err := db.QueryRow(stmts[j].insert, w).Scan(&id)
				mu.Lock()
				var pe *pgconn.PgError
				switch {
				case err == nil:
					res.ids[stmts[j].table] = append(res.ids[stmts[j].table], id)
				case errors.As(err, &pe) && pe.Code == "23505":
					res.dups++
					if len(res.other) < 20 {
						res.other = append(res.other, fmt.Sprintf("%s: duplicate key: %v", stmts[j].table, err))
					}
				default:
					if len(res.other) < 20 {
						res.other = append(res.other, fmt.Sprintf("%s: %v", stmts[j].table, err))
					}
				}
				mu.Unlock()
			}
		}(w)
	}
	wg.Wait()
	return res
}

// checkBurst: 0 lỗi trùng khóa, 0 lỗi khác, đủ perTable row mỗi bảng, id khác nhau và mọi id mới
// > floor[bảng] (id lớn nhất đã replicate, và với sequence độc lập cả last_value của source).
func checkBurst(t *testing.T, dst *pgNode, res g2BurstResult, floor map[string]int64, before map[string]int, perTable int) {
	t.Helper()
	if res.dups != 0 || len(res.other) != 0 {
		t.Fatalf("application inserts right after promote: %d duplicate-key errors, errors:\n%s", res.dups, strings.Join(res.other, "\n"))
	}
	tables := make([]string, 0, len(floor))
	for tb := range floor {
		tables = append(tables, tb)
	}
	sort.Strings(tables)
	for _, tb := range tables {
		ids := res.ids[tb]
		if len(ids) != perTable {
			t.Fatalf("%s: application inserted %d rows, want %d", tb, len(ids), perTable)
		}
		seen := map[int64]bool{}
		minID := ids[0]
		for _, id := range ids {
			if seen[id] {
				t.Fatalf("%s: id %d returned twice", tb, id)
			}
			seen[id] = true
			if id <= floor[tb] {
				t.Fatalf("%s: new id %d is not above every replicated id / source sequence value (floor %d)", tb, id, floor[tb])
			}
			if id < minID {
				minID = id
			}
		}
		var n int
		if err := dst.DB.QueryRow("SELECT count(*) FROM " + tb).Scan(&n); err != nil {
			t.Fatal(err)
		}
		if n != before[tb]+perTable {
			t.Fatalf("%s: %d rows after the burst, want %d + %d", tb, n, before[tb], perTable)
		}
		t.Logf("%s: %d application rows, smallest new id %d > floor %d (gap %d)", tb, perTable, minID, floor[tb], minID-floor[tb])
	}
}

// pgAppStmts: insert bằng giá trị mặc định cho các bảng PG→PG.
var pgAppStmts = []g2AppStmt{
	{"app.g_always", "INSERT INTO app.g_always (n, note) VALUES ($1, 'app') RETURNING id"},
	{"app.g_bydefault", "INSERT INTO app.g_bydefault (n, note) VALUES ($1, 'app') RETURNING id"},
	{"app.g_indep", "INSERT INTO app.g_indep (n, note) VALUES ($1, 'app') RETURNING id"},
}

// pgFloorsAndCounts: max(id) và số row hiện có ở target cho từng bảng của stmts.
func pgFloorsAndCounts(t *testing.T, dst *pgNode, stmts []g2AppStmt) (map[string]int64, map[string]int) {
	floor := map[string]int64{}
	before := map[string]int{}
	for _, s := range stmts {
		floor[s.table] = pgMaxID(t, dst.DB, s.table)
		var n int
		if err := dst.DB.QueryRow("SELECT count(*) FROM " + s.table).Scan(&n); err != nil {
			t.Fatal(err)
		}
		before[s.table] = n
	}
	return floor, before
}

// requireSeqBehind: trước promote, sequence ở target phải còn sau max(id) đã replicate — nếu không,
// test không chứng minh được gì (insert sẽ không trùng khóa kể cả khi promote không setval).
func requireSeqBehind(t *testing.T, dst *pgNode, table, seq string) {
	t.Helper()
	last, _ := pgSeqState(t, dst.DB, seq)
	mx := pgMaxID(t, dst.DB, table)
	if mx <= last {
		t.Fatalf("precondition: target sequence %s (last_value %d) is not behind max(id) %d of %s", seq, last, mx, table)
	}
	t.Logf("before promote: target %s last_value %d < max(%s.id) %d → without setval the next insert collides", seq, last, table, mx)
}

// requireAppCannotWrite: role ứng dụng chưa ghi được vào target (chưa mở ghi).
func requireAppCannotWrite(t *testing.T, appDSN, insert string) {
	t.Helper()
	db, err := sql.Open("pgx", appDSN)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	var id int64
	if err := db.QueryRow(insert, 0).Scan(&id); err == nil {
		t.Fatalf("application wrote to the target (id %d) before promote finished", id)
	} else {
		t.Logf("application still blocked on target: %v", err)
	}
}

