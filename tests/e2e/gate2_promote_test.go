// g2PGTables: bảng ứng dụng của lược đồ PG→PG (app.marker dùng cho waitPGCaughtUp).
var g2PGTables = []string{"app.g_always", "app.g_bydefault", "app.g_indep", "app.marker"}

// g2PGSchema: identity ALWAYS (CACHE identCache), identity BY DEFAULT (START 1000, CACHE 1) và bảng
// lấy id từ sequence độc lập app.ext_seq (DEFAULT nextval, không OWNED BY → promote coi là độc lập,
// lấy last_value của source + margin; 02 §8). Cùng DDL ở source và target (kể cả CACHE).
func g2PGSchema(identCache, seqCache int) []string {
	return []string{
		"CREATE SCHEMA app",
		fmt.Sprintf("CREATE SEQUENCE app.ext_seq START 1 CACHE %d", seqCache),
		fmt.Sprintf("CREATE TABLE app.g_always (id bigint GENERATED ALWAYS AS IDENTITY (CACHE %d) PRIMARY KEY, n int NOT NULL, note text)", identCache),
		"CREATE TABLE app.g_bydefault (id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY, n int NOT NULL, note text)",
		"CREATE TABLE app.g_indep (id bigint PRIMARY KEY DEFAULT nextval('app.ext_seq'), n int NOT NULL, note text)",
		"CREATE TABLE app.marker (id bigint PRIMARY KEY, tag text)",
	}
}

// g2AppRoleSQL: role ứng dụng trên target PG chỉ có quyền đọc trước promote (03 §2); promote
// (--app-role app_rw) giữ read-only ở bước 2 và cấp quyền ghi ở bước 5.
func g2AppRoleSQL(schema string) []string {
	return []string{
		"CREATE ROLE app_rw LOGIN PASSWORD 'app'",
		"GRANT USAGE ON SCHEMA " + schema + " TO app_rw",
		"GRANT SELECT ON ALL TABLES IN SCHEMA " + schema + " TO app_rw",
	}
}

// setupG2PGPair dựng PG→PG: lược đồ giống hệt (bảng rỗng), role ứng dụng ở target, publication,
// rồi slot (two_phase) — mọi row đều tới target qua stream, nên sequence/identity ở target vẫn ở
// giá trị đầu (writer ghi id tường minh, OVERRIDING SYSTEM VALUE): không setval thì chắc chắn trùng khóa.
func setupG2PGPair(t *testing.T, slot, pub string, identCache, seqCache int) (*pgNode, *pgNode, string) {
	t.Helper()
	src := startPG(t, "pgsrc")
	dst := startPG(t, "pgdst")
	src.exec(t, g2PGSchema(identCache, seqCache)...)
	dst.exec(t, g2PGSchema(identCache, seqCache)...)
	dst.exec(t, g2AppRoleSQL("app")...)
	src.exec(t, fmt.Sprintf("CREATE PUBLICATION %s FOR TABLE %s WITH (publish = 'insert, update, delete')", pub, strings.Join(g2PGTables, ", ")))
	var lsn string
	if err := src.DB.QueryRow("SELECT lsn::text FROM pg_create_logical_replication_slot($1, 'pgoutput', false, true)", slot).Scan(&lsn); err != nil {
		t.Fatalf("create slot: %v", err)
	}
	t.Logf("slot %s consistent_point %s", slot, lsn)
	return src, dst, lsn
}

// g2Load: bộ sinh tải đơn giản, nhiều client song song, mỗi client một rand riêng (tất định theo seed).
type g2Load struct {
	stopped atomic.Bool
	wg      sync.WaitGroup
	ops     atomic.Int64
	errs    atomic.Int64
	mu      sync.Mutex
	lastErr string
}

func startG2Load(seed int64, clients int, one func(r *rand.Rand) error) *g2Load {
	l := &g2Load{}
	root := rand.New(rand.NewSource(seed))
	for c := 0; c < clients; c++ {
		r := rand.New(rand.NewSource(root.Int63()))
		l.wg.Add(1)
		go func() {
			defer l.wg.Done()
			for !l.stopped.Load() {
				if err := one(r); err != nil {
					l.errs.Add(1)
					l.mu.Lock()
					l.lastErr = err.Error()
					l.mu.Unlock()
				}
				l.ops.Add(1)
			}
		}()
	}
	return l
}

func (l *g2Load) Stop() {
	l.stopped.Store(true)
	l.wg.Wait()
}

func (l *g2Load) summary() string {
	l.mu.Lock()
	defer l.mu.Unlock()
	return fmt.Sprintf("%d ops, %d client-side errors (last: %q)", l.ops.Load(), l.errs.Load(), l.lastErr)
}

// g2PGOp: một thao tác trên source PG — insert bằng giá trị mặc định (identity / nextval, nhiều
// session nên mỗi session giữ cache riêng), Txn nhiều row, update, xóa ngẫu nhiên gần đỉnh và xóa
// đúng row có id lớn nhất (max(cột) ở target khi đó nhỏ hơn giá trị sequence đã cấp ở source).
func g2PGOp(db *sql.DB) func(r *rand.Rand) error {
	tables := []string{"app.g_always", "app.g_bydefault", "app.g_indep"}
	return func(r *rand.Rand) error {
		tb := tables[r.Intn(len(tables))]
		switch k := r.Intn(100); {
		case k < 45:
			var id int64
			return db.QueryRow("INSERT INTO "+tb+" (n, note) VALUES ($1, 'src') RETURNING id", r.Intn(1000)).Scan(&id)
		case k < 55:
			_, err := db.Exec("INSERT INTO " + tb + " (n, note) SELECT g, 'batch' FROM generate_series(1, 25) g")
			return err
		case k < 85:
			_, err := db.Exec("UPDATE "+tb+" SET n = n + 1, note = 'upd' WHERE id = (SELECT id FROM "+tb+" ORDER BY id DESC OFFSET $1 LIMIT 1)", r.Intn(200))
			return err
		case k < 97:
			_, err := db.Exec("DELETE FROM "+tb+" WHERE id = (SELECT id FROM "+tb+" ORDER BY id DESC OFFSET $1 LIMIT 1)", 10+r.Intn(300))
			return err
		default:
			_, err := db.Exec("DELETE FROM " + tb + " WHERE id = (SELECT max(id) FROM " + tb + ")")
			return err
		}
	}
}

// pgDSNAs đổi user/password của DSN PG dạng URL (giữ host, port, database, tham số).
func pgDSNAs(t *testing.T, dsn, user, pass string) string {
	t.Helper()
	u, err := url.Parse(dsn)
	if err != nil {
		t.Fatalf("parse DSN: %v", err)
	}
	u.User = url.UserPassword(user, pass)
	return u.String()
}

// withParam thêm tham số query vào DSN (URL PG hoặc DSN go-sql-driver).
func withParam(dsn, kv string) string {
	if strings.Contains(dsn, "?") {
		return dsn + "&" + kv
	}
	return dsn + "?" + kv
}

// pauseContainer đóng băng container (docker pause): source không trả lời nhưng cổng vẫn giữ —
// "Strand không thấy source" chứ không phải "source đã chết". Cleanup unpause để Terminate chạy được.
func pauseContainer(t *testing.T, c testcontainers.Container) {
	t.Helper()
	id := c.GetContainerID()
	runDockerCmd(t, time.Minute, "pause", id)
	t.Cleanup(func() { _ = exec.Command("docker", "unpause", id).Run() })
}

// pgMaxID: max(id) của bảng (0 nếu rỗng).
func pgMaxID(t *testing.T, db *sql.DB, table string) int64 {
	t.Helper()
	var v int64
	if err := db.QueryRow("SELECT COALESCE(max(id), 0)::bigint FROM " + table).Scan(&v); err != nil {
		t.Fatalf("max(id) of %s: %v", table, err)
	}
	return v
}

// pgSeqState: last_value và is_called của sequence (đọc thẳng relation sequence).
func pgSeqState(t *testing.T, db *sql.DB, seq string) (int64, bool) {
	t.Helper()
	var v int64
	var called bool
	if err := db.QueryRow("SELECT last_value, is_called FROM "+seq).Scan(&v, &called); err != nil {
		t.Fatalf("read sequence %s: %v", seq, err)
	}
	return v, called
}

// promoteRow: trạng thái promote đã lưu ở target (_strand_promote).
type promoteRow struct {
	State     string
	Steps     []string
	Suggested map[string]int64
}

func loadPromoteRow(t *testing.T, dst *pgNode, pipeline string) promoteRow {
	t.Helper()
	var r promoteRow
	var steps string
	var sugg sql.NullString
	if err := dst.DB.QueryRow("SELECT state, completed_steps::text, suggested_sequences::text FROM _strand_promote WHERE pipeline_id = $1", pipeline).
		Scan(&r.State, &steps, &sugg); err != nil {
		t.Fatalf("read _strand_promote: %v", err)
	}
	if err := json.Unmarshal([]byte(steps), &r.Steps); err != nil {
		t.Fatalf("completed_steps %q: %v", steps, err)
	}
	if sugg.Valid && sugg.String != "" && sugg.String != "null" {
		if err := json.Unmarshal([]byte(sugg.String), &r.Suggested); err != nil {
			t.Fatalf("suggested_sequences %q: %v", sugg.String, err)
		}
	}
	return r
}

func (r promoteRow) has(step string) bool {
	for _, s := range r.Steps {
		if s == step {
			return true
		}
	}
	return false
}

// syncedValue: LastSyncedValue của sequence trong _strand_promote (do sync định kỳ ghi), 0 nếu chưa có.
func syncedValue(dst *pgNode, pipeline, seq string) int64 {
	var v sql.NullInt64
	_ = dst.DB.QueryRow(`SELECT max((s->>'last_synced_value')::bigint) FROM _strand_promote, jsonb_array_elements(sequences) s
		WHERE pipeline_id = $1 AND s->>'name' = $2`, pipeline, seq).Scan(&v)
	return v.Int64
}

