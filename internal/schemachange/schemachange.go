// Package schemachange lưu các thay đổi schema đang chờ duyệt (P3-01) trong bảng _strand_schema_change ở
// target — cùng chỗ với các bảng trạng thái khác của Strand (_strand_pipeline, _strand_checkpoint) — và áp
// chúng khi người vận hành chạy `strand schema approve`.
package schemachange

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"fmt"
	"strconv"
	"strings"

	"strand/internal/exitcode"
	"strand/internal/schemagen"
)

// Trạng thái của một thay đổi.
const (
	StatusPending  = "pending"
	StatusApproved = "approved" // đã nhận lệnh approve, đang/đã dở dang áp DDL
	StatusApplied  = "applied"
)

const table = "_strand_schema_change"

// Change là một dòng của bảng _strand_schema_change.
type Change struct {
	ID             int64
	Pipeline       string
	SourcePos      string   // nhãn vị trí DDL ở source
	SourceDDL      string   // DDL gốc ở source
	Statements     []string // DDL đề xuất cho target, theo thứ tự áp
	Classification string   // additive | destructive
	Reason         string   // mô tả các thay đổi
	Status         string
	CreatedAt      string // văn bản (DSN MySQL không nhất thiết bật parseTime)
}

// Store truy cập bảng trạng thái. pg: target là PostgreSQL.
type Store struct {
	db *sql.DB
	pg bool
}

// NewStore tạo Store trên kết nối target.
func NewStore(db *sql.DB, pg bool) *Store { return &Store{db: db, pg: pg} }

func (s *Store) q(query string) string {
	if !s.pg {
		return query
	}
	var b strings.Builder
	n := 0
	for _, r := range query {
		if r == '?' {
			n++
			b.WriteString("$" + strconv.Itoa(n))
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// EnsureTable tạo bảng nếu chưa có.
func (s *Store) EnsureTable(ctx context.Context) error {
	ddl := `CREATE TABLE IF NOT EXISTS ` + table + ` (
			id             BIGINT AUTO_INCREMENT PRIMARY KEY,
			pipeline_id    VARCHAR(64)  NOT NULL,
			source_pos     VARCHAR(255) NOT NULL,
			source_ddl     MEDIUMTEXT   NOT NULL,
			proposed_ddl   MEDIUMTEXT   NOT NULL,
			classification VARCHAR(16)  NOT NULL,
			reason         TEXT         NOT NULL,
			status         VARCHAR(16)  NOT NULL,
			created_at     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
			applied_at     TIMESTAMP(6) NULL,
			KEY idx_pipeline_status (pipeline_id, status)
		) ENGINE=InnoDB`
	if s.pg {
		ddl = `CREATE TABLE IF NOT EXISTS ` + table + ` (
			id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			pipeline_id    text NOT NULL,
			source_pos     text NOT NULL,
			source_ddl     text NOT NULL,
			proposed_ddl   text NOT NULL,
			classification text NOT NULL,
			reason         text NOT NULL,
			status         text NOT NULL,
			created_at     timestamptz NOT NULL DEFAULT now(),
			applied_at     timestamptz NULL
		)`
	}
	if _, err := s.db.ExecContext(ctx, ddl); err != nil {
		return fmt.Errorf("create %s: %w", table, err)
	}
	return nil
}

// Record ghi một thay đổi đang chờ. Cùng pipeline + vị trí + DDL đề xuất mà còn pending/approved thì dùng lại
// dòng cũ (pipeline chạy lại sẽ xử lý lại cùng DDL), trả created=false.
func (s *Store) Record(ctx context.Context, c Change) (id int64, created bool, err error) {
	if err := s.EnsureTable(ctx); err != nil {
		return 0, false, err
	}
	stmts, err := json.Marshal(c.Statements)
	if err != nil {
		return 0, false, err
	}
	err = s.db.QueryRowContext(ctx, s.q(`SELECT id FROM `+table+` WHERE pipeline_id=? AND source_pos=? AND proposed_ddl=? AND status IN ('pending','approved') ORDER BY id LIMIT 1`),
		c.Pipeline, c.SourcePos, string(stmts)).Scan(&id)
	if err == nil {
		return id, false, nil
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return 0, false, err
	}
	ins := `INSERT INTO ` + table + ` (pipeline_id, source_pos, source_ddl, proposed_ddl, classification, reason, status) VALUES (?, ?, ?, ?, ?, ?, 'pending')`
	args := []any{c.Pipeline, c.SourcePos, c.SourceDDL, string(stmts), c.Classification, c.Reason}
	if s.pg {
		err = s.db.QueryRowContext(ctx, s.q(ins+` RETURNING id`), args...).Scan(&id)
		return id, err == nil, err
	}
	res, err := s.db.ExecContext(ctx, ins, args...)
	if err != nil {
		return 0, false, err
	}
	id, err = res.LastInsertId()
	return id, err == nil, err
}

// ResolveAt đánh dấu applied mọi thay đổi còn pending/approved tại vị trí pos (DBA đã tự áp DDL ở target).
func (s *Store) ResolveAt(ctx context.Context, pipeline, pos string) error {
	if !s.exists(ctx) {
		return nil
	}
	_, err := s.db.ExecContext(ctx, s.q(`UPDATE `+table+` SET status='applied', applied_at=`+s.now()+` WHERE pipeline_id=? AND source_pos=? AND status IN ('pending','approved')`), pipeline, pos)
	return err
}

func (s *Store) now() string {
	if s.pg {
		return "now()"
	}
	return "CURRENT_TIMESTAMP(6)"
}

func (s *Store) exists(ctx context.Context) bool {
	_, err := s.db.ExecContext(ctx, `SELECT 1 FROM `+table+` WHERE 1=0`)
	return err == nil
}

func scan(rows interface{ Scan(...any) error }) (Change, error) {
	var c Change
	var stmts string
	if err := rows.Scan(&c.ID, &c.Pipeline, &c.SourcePos, &c.SourceDDL, &stmts, &c.Classification, &c.Reason, &c.Status, &c.CreatedAt); err != nil {
		return c, err
	}
	if err := json.Unmarshal([]byte(stmts), &c.Statements); err != nil {
		return c, fmt.Errorf("decode proposed_ddl of change %d: %w", c.ID, err)
	}
	return c, nil
}

func (s *Store) cols() string {
	ts := "CAST(created_at AS CHAR)"
	if s.pg {
		ts = "created_at::text"
	}
	return `id, pipeline_id, source_pos, source_ddl, proposed_ddl, classification, reason, status, ` + ts
}

// List trả các thay đổi của pipeline (mặc định chỉ pending/approved; all=true gồm cả applied), theo id tăng.
func (s *Store) List(ctx context.Context, pipeline string, all bool) ([]Change, error) {
	if !s.exists(ctx) {
		return nil, nil
	}
	q := `SELECT ` + s.cols() + ` FROM ` + table + ` WHERE pipeline_id=?`
	if !all {
		q += ` AND status IN ('pending','approved')`
	}
	rows, err := s.db.QueryContext(ctx, s.q(q+` ORDER BY id`), pipeline)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []Change
	for rows.Next() {
		c, err := scan(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, c)
	}
	return out, rows.Err()
}

// Get đọc một thay đổi theo id; ErrNotFound khi không có.
func (s *Store) Get(ctx context.Context, id int64) (Change, error) {
	if !s.exists(ctx) {
		return Change{}, ErrNotFound
	}
	c, err := scan(s.db.QueryRowContext(ctx, s.q(`SELECT `+s.cols()+` FROM `+table+` WHERE id=?`), id))
	if errors.Is(err, sql.ErrNoRows) {
		return Change{}, ErrNotFound
	}
	return c, err
}

// ErrNotFound: không có thay đổi với id đó.
var ErrNotFound = errors.New("schema change not found")

// Approve áp DDL đề xuất của thay đổi id lên target theo thứ tự rồi đánh dấu applied. Trả (đã áp, lỗi).
// Idempotent: id đã applied thì không làm gì (applied=false, err=nil). dryRun chỉ trả danh sách câu sẽ chạy
// (out) mà không đổi gì. PG chạy mọi câu và đánh dấu trong một transaction; MySQL DDL tự commit từng câu —
// nếu bị ngắt giữa chừng, trạng thái là approved và chạy lại approve sẽ chạy lại từ câu đầu (câu đã áp sẽ báo
// lỗi trùng; khi đó áp nốt phần còn lại bằng tay rồi chạy `strand sync`, bước so schema sẽ đi tiếp).
func (s *Store) Approve(ctx context.Context, pipeline string, id int64, dryRun bool) (c Change, applied bool, err error) {
	if c, err = s.Get(ctx, id); err != nil {
		if errors.Is(err, ErrNotFound) {
			return c, false, exitcode.New("schema_change_not_found", exitcode.InvalidSyntax, fmt.Sprintf("schema change %d not found", id), err)
		}
		return c, false, err
	}
	if c.Pipeline != pipeline {
		return c, false, exitcode.New("schema_change_not_found", exitcode.InvalidSyntax, fmt.Sprintf("schema change %d belongs to pipeline %q, not %q", id, c.Pipeline, pipeline), nil)
	}
	if c.Status == StatusApplied {
		return c, false, nil
	}
	for _, st := range c.Statements {
		if schemagen.IsManualStatement(st) {
			return c, false, exitcode.New("schema_change_manual", exitcode.NeedsDecision,
				fmt.Sprintf("schema change %d contains a change Strand does not apply automatically (%s). Apply it on the target yourself, then run strand sync again", id, strings.TrimPrefix(st, schemagen.ManualPrefix)), nil)
		}
	}
	if dryRun {
		return c, false, nil
	}
	if s.pg {
		tx, err := s.db.BeginTx(ctx, nil)
		if err != nil {
			return c, false, err
		}
		defer tx.Rollback()
		for i, st := range c.Statements {
			if _, err := tx.ExecContext(ctx, st); err != nil {
				return c, false, fmt.Errorf("schema change %d: statement %d/%d failed: %w (%s)", id, i+1, len(c.Statements), err, st)
			}
		}
		if _, err := tx.ExecContext(ctx, s.q(`UPDATE `+table+` SET status='applied', applied_at=now() WHERE id=?`), id); err != nil {
			return c, false, err
		}
		if err := tx.Commit(); err != nil {
			return c, false, err
		}
		c.Status = StatusApplied
		return c, true, nil
	}
	if _, err := s.db.ExecContext(ctx, `UPDATE `+table+` SET status='approved' WHERE id=? AND status='pending'`, id); err != nil {
		return c, false, err
	}
	for i, st := range c.Statements {
		if _, err := s.db.ExecContext(ctx, st); err != nil {
			return c, false, fmt.Errorf("schema change %d: statement %d/%d failed: %w (%s)", id, i+1, len(c.Statements), err, st)
		}
	}
	if _, err := s.db.ExecContext(ctx, `UPDATE `+table+` SET status='applied', applied_at=CURRENT_TIMESTAMP(6) WHERE id=?`, id); err != nil {
		return c, false, err
	}
	c.Status = StatusApplied
	return c, true, nil
}
