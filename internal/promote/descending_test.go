package promote_test

// Review 4.3: sequence giảm dần (INCREMENT âm). Trước đây promote lấy max(cột)+margin / last_value+margin
// và setval(GREATEST(...)) — tức đưa sequence QUAY LẠI vùng giá trị đã cấp → trùng khóa sau promote.

import (
	"context"
	"fmt"
	"testing"
	"time"

	"strand/internal/promote"
)

func TestCalculateMarginUsesAbsIncrement(t *testing.T) {
	if a, b := promote.CalculateMargin(10, -3, 100, 2), promote.CalculateMargin(10, 3, 100, 2); a != b {
		t.Fatalf("margin for increment -3 = %d, want same as +3 = %d", a, b)
	}
}

func TestReview43_DescendingSequencesPromote(t *testing.T) {
	ctx := context.Background()
	srcSrv, tgtSrv := sourcePG(t), targetPG(t)
	srcDB, _ := newTestDB(t, srcSrv)
	tgtDB, tgtDSN := newTestDB(t, tgtSrv)
	unfenceOnCleanup(t, srcSrv)

	// Sequence độc lập giảm dần trên source: đã cấp 1000, 998, 996 (cache 1 để last_value = giá trị cuối).
	ddlIndep := `CREATE SEQUENCE desc_global_seq INCREMENT -2 MINVALUE -1000000 MAXVALUE 1000 START 1000 CACHE 1;
		CREATE TABLE desc_orders (id BIGINT PRIMARY KEY DEFAULT nextval('desc_global_seq'), val TEXT)`
	mustExec(t, srcDB, ddlIndep)
	for i := 0; i < 3; i++ {
		mustExec(t, srcDB, "INSERT INTO desc_orders (val) VALUES ('src')")
	}
	srcLast := seqLastValue(t, srcDB, "desc_global_seq")
	if srcLast != 996 {
		t.Fatalf("source last_value = %d, want 996", srcLast)
	}

	role := createAppRole(t, tgtSrv, "desc_app")
	mustExec(t, tgtDB, ddlIndep)
	mustExec(t, tgtDB, "INSERT INTO desc_orders VALUES (1000, 'src'), (998, 'src'), (996, 'src')")
	// Identity giảm dần (mặc định START -1, MAXVALUE -1): đã cấp -1, -2, -3 và có row replicate -150.
	mustExec(t, tgtDB, `
		CREATE TABLE desc_items (id BIGINT GENERATED BY DEFAULT AS IDENTITY (INCREMENT -1 CACHE 5) PRIMARY KEY, title TEXT);
		INSERT INTO desc_items (title) VALUES ('a'), ('b'), ('c');
		INSERT INTO desc_items VALUES (-150, 'replicated row -150');`)
	mustExec(t, tgtDB, fmt.Sprintf("GRANT USAGE ON SCHEMA public TO %s; GRANT SELECT ON ALL TABLES IN SCHEMA public TO %s", role, role))

	pid := "desc-pipeline"
	simulatePipeline(t, srcDB, tgtDB, pid)
	seqs, err := promote.DiscoverPGSequences(ctx, tgtDB, []string{"public"})
	if err != nil {
		t.Fatal(err)
	}
	indep := findSeq(t, seqs, "desc_global_seq")
	ident := findSeq(t, seqs, "desc_items_id_seq")
	if indep.Type != promote.SequenceTypeIndependent || indep.IncrementBy != -2 || ident.Type != promote.SequenceTypeColumn || ident.IncrementBy != -1 {
		t.Fatalf("discovered: %+v / %+v", indep, ident)
	}
	cfg := promote.Config{PipelineID: pid, PeakRate: 10, SyncIntervalSec: 1}
	mIndep := promote.CalculateMargin(1, -2, 10, 1)
	mIdent := promote.CalculateMargin(5, -1, 10, 1)

	targetDriver := promote.NewPGTargetDriver(tgtDB, role).WithPipeline(pid).WithCatchUpCheck(srcDB, pid, 30*time.Second, nil)
	progress, err := promote.NewPromoter(cfg, promote.NewPGStateStore(tgtDB), promote.NewPGSourceDriver(srcDB), targetDriver, seqs, nil).Run(ctx)
	if err != nil || progress.State != promote.StatePromoted {
		t.Fatalf("promote: %v (%+v)", err, progress)
	}
	if got, want := seqLastValue(t, tgtDB, "desc_global_seq"), srcLast-mIndep; got != want {
		t.Fatalf("independent descending: setval = %d, want source last_value %d - margin %d = %d", got, srcLast, mIndep, want)
	}
	if got, want := seqLastValue(t, tgtDB, "desc_items_id_seq"), int64(-150)-mIdent; got != want {
		t.Fatalf("identity descending: setval = %d, want min(col) -150 - margin %d = %d", got, mIdent, want)
	}

	// Ứng dụng ghi sau promote: id mới phải thấp hơn mọi id đã dùng, không trùng khóa.
	app := openAs(t, tgtSrv, tgtDSN, role)
	for i := 0; i < 3; i++ {
		var id int64
		if err := app.QueryRowContext(ctx, "INSERT INTO desc_orders (val) VALUES ('post') RETURNING id").Scan(&id); err != nil {
			t.Fatalf("app insert desc_orders: %v", err)
		}
		if id >= 996 {
			t.Fatalf("new desc_orders id %d not below used values", id)
		}
		if err := app.QueryRowContext(ctx, "INSERT INTO desc_items (title) VALUES ('post') RETURNING id").Scan(&id); err != nil {
			t.Fatalf("app insert desc_items: %v", err)
		}
		if id >= -150 {
			t.Fatalf("new desc_items id %d not below used values", id)
		}
	}
}
