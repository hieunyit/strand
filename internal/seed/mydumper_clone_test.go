// TestSD1_SeedPlan_MydumperAndClone_CrossCheck kiểm tra AC1 (P1-13):
// seed plan đọc P từ metadata của mydumper và CLONE, đối chiếu chéo với target đã restore (SD-1).
func TestSD1_SeedPlan_MydumperAndClone_CrossCheck(t *testing.T) {
	gtid := "3E11FA47-71CA-11E1-9E33-C80AA9429562:1-982341"
	ctx := context.Background()

	schemaBytes, err := os.ReadFile("../../schema/seed.schema.json")
	if err != nil {
		t.Fatalf("read seed.schema.json failed: %v", err)
	}
	validator, err := schema.NewSeedSchemaValidator(schemaBytes)
	if err != nil {
		t.Fatalf("create validator failed: %v", err)
	}

	// 1. mydumper
	t.Run("Mydumper", func(t *testing.T) {
		dir := t.TempDir()
		metaContent := `# Generated by mydumper v1.0.3-1
Log: binlog.000001
Pos: 12345
GTID: ` + gtid + `
Lock Mode: LOCK TABLES
`
		if err := os.WriteFile(filepath.Join(dir, "metadata"), []byte(metaContent), 0644); err != nil {
			t.Fatalf("write metadata failed: %v", err)
		}

		planner := seed.NewMydumperPlanner()
		src := seed.SeedSource{
			Engine:             "mysql",
			Kind:               "mydumper",
			BackupRef:          dir,
			Tables:             []string{"app.orders"},
			TargetVersion:      "8.4.6",
			TargetRestoredGTID: gtid,
		}

		manifest, err := planner.Plan(ctx, src)
		if err != nil {
			t.Fatalf("mydumper Plan failed: %v", err)
		}

		if manifest.StartPosition.GTIDSet != gtid {
			t.Fatalf("expected GTIDSet %s, got %s", gtid, manifest.StartPosition.GTIDSet)
		}
		if manifest.PositionCrossCheck == nil || !manifest.PositionCrossCheck.Match {
			t.Fatalf("expected PositionCrossCheck.Match == true")
		}
		if manifest.Kind != "mydumper" {
			t.Fatalf("expected kind mydumper, got %s", manifest.Kind)
		}

		// Kiểm thực schema
		manifestJSON, err := json.Marshal(manifest)
		if err != nil {
			t.Fatalf("marshal manifest failed: %v", err)
		}
		if err := validator.Validate(manifestJSON); err != nil {
			t.Fatalf("manifest failed seed.schema.json validation: %v", err)
		}
		t.Logf("PASS: mydumper manifest matches seed.schema.json")
	})

	// 2. CLONE
	t.Run("CLONE", func(t *testing.T) {
		planner := seed.NewClonePlanner()
		src := seed.SeedSource{
			Engine:             "mysql",
			Kind:               "clone",
			TargetVersion:      "8.4.6",
			TargetRestoredGTID: gtid,
			Tables:             []string{"app.orders"},
		}

		manifest, err := planner.Plan(ctx, src)
		if err != nil {
			t.Fatalf("clone Plan failed: %v", err)
		}

		if manifest.StartPosition.GTIDSet != gtid {
			t.Fatalf("expected GTIDSet %s, got %s", gtid, manifest.StartPosition.GTIDSet)
		}
		if manifest.Kind != "clone" {
			t.Fatalf("expected kind clone, got %s", manifest.Kind)
		}

		// Kiểm thực schema
		manifestJSON, err := json.Marshal(manifest)
		if err != nil {
			t.Fatalf("marshal manifest failed: %v", err)
		}
		if err := validator.Validate(manifestJSON); err != nil {
			t.Fatalf("manifest failed seed.schema.json validation: %v", err)
		}
		t.Logf("PASS: CLONE manifest matches seed.schema.json")
	})

	t.Logf("PASS AC1: seed plan reads P from metadata for mydumper and CLONE, cross-checks successfully")
}

// TestSD2_MydumperAndClone_CorruptedBackup_Rejected kiểm tra AC2 (P1-13):
// Backup hỏng (thiếu file, sai GTID, log có khoảng trống) bị từ chối 100%.
func TestSD2_MydumperAndClone_CorruptedBackup_Rejected(t *testing.T) {
	ctx := context.Background()
	mydumperPlanner := seed.NewMydumperPlanner()
	clonePlanner := seed.NewClonePlanner()

	// 1. mydumper: Thiếu file metadata
	t.Run("MydumperMissingMetadata", func(t *testing.T) {
		dir := t.TempDir()
		_, err := mydumperPlanner.Plan(ctx, seed.SeedSource{BackupRef: dir})
		if err == nil {
			t.Fatalf("expected error for missing metadata, got nil")
		}
		if code := exitcode.GetExitCode(err); code != exitcode.Rejected {
			t.Fatalf("expected exit code %d, got %d", exitcode.Rejected, code)
		}
	})

	// 2. mydumper: Thiếu GTID
	t.Run("MydumperMissingGTID", func(t *testing.T) {
		dir := t.TempDir()
		meta := "Log: binlog.000001\nPos: 12345\nLock Mode: BACKUP STAGE\n"
		_ = os.WriteFile(filepath.Join(dir, "metadata"), []byte(meta), 0644)
		_, err := mydumperPlanner.Plan(ctx, seed.SeedSource{BackupRef: dir})
		if err == nil {
			t.Fatalf("expected error for missing GTID, got nil")
		}
		if code := exitcode.GetExitCode(err); code != exitcode.Rejected {
			t.Fatalf("expected exit code %d, got %d", exitcode.Rejected, code)
		}
	})

	// 3. mydumper: GTID có khoảng trống (holes)
	t.Run("MydumperGTIDWithHoles", func(t *testing.T) {
		dir := t.TempDir()
		meta := "Log: binlog.000001\nPos: 12345\nGTID: uuid:1-10:20-30\nLock Mode: LOCK TABLES\n"
		_ = os.WriteFile(filepath.Join(dir, "metadata"), []byte(meta), 0644)
		_, err := mydumperPlanner.Plan(ctx, seed.SeedSource{BackupRef: dir})
		if err == nil {
			t.Fatalf("expected error for GTID with holes, got nil")
		}
		if code := exitcode.GetExitCode(err); code != exitcode.DataError {
			t.Fatalf("expected exit code %d (DataError / log_gap), got %d", exitcode.DataError, code)
		}
	})

	// 4. CLONE: Thiếu GTID
	t.Run("CloneMissingGTID", func(t *testing.T) {
		_, err := clonePlanner.Plan(ctx, seed.SeedSource{Kind: "clone"})
		if err == nil {
			t.Fatalf("expected error for missing GTID in clone, got nil")
		}
		if code := exitcode.GetExitCode(err); code != exitcode.Rejected {
			t.Fatalf("expected exit code %d, got %d", exitcode.Rejected, code)
		}
	})

	// 5. CLONE: GTID có holes
	t.Run("CloneGTIDWithHoles", func(t *testing.T) {
		_, err := clonePlanner.Plan(ctx, seed.SeedSource{
			Kind:               "clone",
			TargetRestoredGTID: "uuid:1-10:20-30",
		})
		if err == nil {
			t.Fatalf("expected error for clone GTID with holes, got nil")
		}
		if code := exitcode.GetExitCode(err); code != exitcode.DataError {
			t.Fatalf("expected exit code %d (DataError / log_gap), got %d", exitcode.DataError, code)
		}
	})

	t.Logf("PASS AC2: Corrupted backup for mydumper and CLONE rejected 100%%")
}

// TestSD1_Mydumper_NoLock_Rejected kiểm tra AC3 (P1-13):
// mydumper chạy chế độ NO_LOCK bị từ chối 100% (spec: 02 §9, design §3.3).
func TestSD1_Mydumper_NoLock_Rejected(t *testing.T) {
	ctx := context.Background()
	planner := seed.NewMydumperPlanner()

	noLockVariations := []string{
		"Lock Mode: NO_LOCK",
		"lock_mode = NO_LOCK",
		"Lock Mode: no_lock",
		"Lock Mode: NO-LOCK",
		"--no-locks = true",
	}

	for _, variation := range noLockVariations {
		dir := t.TempDir()
		content := "# Generated by mydumper v1.0.3-1\nLog: binlog.000001\nPos: 100\nGTID: uuid:1-100\n" + variation + "\n"
		if err := os.WriteFile(filepath.Join(dir, "metadata"), []byte(content), 0644); err != nil {
			t.Fatalf("write file failed: %v", err)
		}

		_, err := planner.Plan(ctx, seed.SeedSource{BackupRef: dir})
		if err == nil {
			t.Fatalf("expected rejection for mydumper %q, got nil", variation)
		}
		if code := exitcode.GetExitCode(err); code != exitcode.Rejected {
			t.Fatalf("expected exit code %d (Rejected), got %d: err=%v", exitcode.Rejected, code, err)
		}
		t.Logf("PASS: rejected %q with exit code 3: %v", variation, err)
	}

	t.Logf("PASS AC3: mydumper with NO_LOCK is rejected 100%% across all variations")
}
