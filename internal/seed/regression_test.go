// invariant: SD-4 / issue 15
// Without xtrabackup_info the tool version was assumed to be "8.4.0-6": an RC
// backup with the info file removed passed both the RC check and SD-4.
func TestSD4_MissingXtrabackupInfoRejected(t *testing.T) {
	src := seed.SeedSource{Engine: "mysql", Kind: "xtrabackup", TargetVersion: "8.4.6",
		BackupRef: xtraDir(t, uA+":1-100", "")}
	_, err := seed.NewXtraBackupPlanner().Plan(context.Background(), src)
	if exitcode.GetExitCode(err) != exitcode.Rejected {
		t.Fatalf("expected rejection when tool version cannot be read, got %v", err)
	}
}

// invariant: SD-4
// Physical backup needs the same version line (8.0 / 8.4 / 9.x) on the target.
// Compatible was hard-coded to true.
func TestSD4_PhysicalBackupVersionLineMismatchRejected(t *testing.T) {
	ctx := context.Background()
	dir := xtraDir(t, uA+":1-100", "tool_version = 8.0.35-30\nserver_version = 8.0.36\n")
	for _, target := range []string{"8.4.6", ""} {
		_, err := seed.NewXtraBackupPlanner().Plan(ctx, seed.SeedSource{Engine: "mysql", Kind: "xtrabackup",
			BackupRef: dir, TargetVersion: target})
		if exitcode.GetExitCode(err) != exitcode.Rejected {
			t.Fatalf("target %q: expected SD-4 rejection for 8.0 backup, got %v", target, err)
		}
	}
	m, err := seed.NewXtraBackupPlanner().Plan(ctx, seed.SeedSource{Engine: "mysql", Kind: "xtrabackup",
		BackupRef: dir, TargetVersion: "8.0.40"})
	if err != nil || !m.Target.Compatible {
		t.Fatalf("same line 8.0 must be accepted: %v", err)
	}
}

// Integrity must reflect the backup state, not be hard-coded to true.
func TestSD1_PrepareOKReflectsBackupType(t *testing.T) {
	ctx := context.Background()
	m, err := seed.NewXtraBackupPlanner().Plan(ctx, seed.SeedSource{Engine: "mysql", Kind: "xtrabackup",
		BackupRef: xtraDir(t, uA+":1-100", goodInfo), TargetVersion: "8.4.6"})
	if err != nil {
		t.Fatal(err)
	}
	if m.Integrity == nil || m.Integrity.PrepareOK {
		t.Fatalf("backup_type=full-backuped is not prepared; prepare_ok must be false")
	}
}

