// invariant: SD-4
// Physical backup needs the same version line (8.0 / 8.4 / 9.x) on the target.
// Compatible was hard-coded to true.
func TestSD4_PhysicalBackupVersionLineMismatchRejected(t *testing.T) {
	ctx := context.Background()
	dir := xtraDir(t, uA+":1-100", "tool_version = 8.0.35-30\nserver_version = 8.0.36\n")
	for _, target := range []string{"8.4.6", ""} {
		_, err := seed.NewXtraBackupPlanner().Plan(ctx, seed.SeedSource{Engine: "mysql", Kind: "xtrabackup",
			BackupRef: dir, TargetVersion: target})
		if exitcode.GetExitCode(err) != exitcode.Rejected {
			t.Fatalf("target %q: expected SD-4 rejection for 8.0 backup, got %v", target, err)
		}
	}
	m, err := seed.NewXtraBackupPlanner().Plan(ctx, seed.SeedSource{Engine: "mysql", Kind: "xtrabackup",
		BackupRef: dir, TargetVersion: "8.0.40", SourceArch: "x86_64", TargetArch: "x86_64"})
	if err != nil || !m.Target.Compatible {
		t.Fatalf("same line 8.0 must be accepted: %v", err)
	}
}

