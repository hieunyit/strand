func xtraDir(t *testing.T, gtid, info string) string {
	files := map[string]string{
		"xtrabackup_checkpoints": "backup_type = full-backuped\nfrom_lsn = 0\nto_lsn = 100\n",
		"xtrabackup_binlog_info": "binlog.000001\t4\t" + gtid + "\n",
		"schema.sql":             "CREATE TABLE app.t (id INT PRIMARY KEY);",
	}
	if info != "" {
		files["xtrabackup_info"] = info
	}
	return createMockXtraBackup(t, files)
}

func mydumperDir(t *testing.T, gtid string) string {
	dir := t.TempDir()
	meta := "# Generated by mydumper v1.0.3-1\nLog: binlog.000001\nPos: 4\nGTID: " + gtid + "\nLock Mode: LOCK TABLES\n"
	if err := os.WriteFile(filepath.Join(dir, "metadata"), []byte(meta), 0644); err != nil {
		t.Fatal(err)
	}
	return dir
}

const goodInfo = "tool_version = 8.4.0-6\nserver_version = 8.4.0\n"

type planFn func(src seed.SeedSource) error

func planners(t *testing.T, gtid string) map[string]planFn {
	ctx := context.Background()
	return map[string]planFn{
		"xtrabackup": func(src seed.SeedSource) error {
			src.Kind, src.BackupRef = "xtrabackup", xtraDir(t, gtid, goodInfo)
			src.SourceArch, src.TargetArch = "x86_64", "x86_64" // SD-4 kiến trúc (review R32)
			_, err := seed.NewXtraBackupPlanner().Plan(ctx, src)
			return err
		},
		"mydumper": func(src seed.SeedSource) error {
			src.Kind, src.BackupRef = "mydumper", mydumperDir(t, gtid)
			src.AcceptUnverifiedLockMode = true // test này kiểm SD-2, không kiểm chế độ khóa
			_, err := seed.NewMydumperPlanner().Plan(ctx, src)
			return err
		},
		"clone": func(src seed.SeedSource) error {
			src.Kind, src.TargetRestoredGTID = "clone", gtid
			_, err := seed.NewClonePlanner().Plan(ctx, src)
			return err
		},
	}
}

// invariant: SD-2
// Old check: "is P's highest GNO purged? then archive must contain P's highest GNO".
// P=1-1000, purged=1-5000, archive=1-2000 passed although 2001-5000 are gone.
func TestSD2_PurgedBeyondArchiveIsLogGap(t *testing.T) {
	for name, plan := range planners(t, uA+":1-1000") {
		t.Run(name, func(t *testing.T) {
			err := plan(seed.SeedSource{Engine: "mysql", TargetVersion: "8.4.6",
				SourcePurgedGTID: uA + ":1-5000", ArchiveUntilGTID: uA + ":1-2000"})
			if exitcode.GetExitCode(err) != exitcode.DataError {
				t.Fatalf("expected log_gap (exit 5), got %v", err)
			}
			err = plan(seed.SeedSource{Engine: "mysql", TargetVersion: "8.4.6",
				SourcePurgedGTID: uA + ":1-5000", ArchiveUntilGTID: uA + ":900-6000"})
			if err != nil {
				t.Fatalf("archive covers 1001-5000, plan must pass: %v", err)
			}
		})
	}
}

