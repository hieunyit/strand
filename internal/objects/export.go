package objects

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Tên tệp xuất.
const (
	FileViewsRoutines = "01-views-routines.sql"
	FileEventsOff     = "02-events-disabled.sql"
	FileTriggers      = "03-triggers.sql"
	FileEventsOn      = "04-events-enable.sql"
	FileUsers         = "users.sql"
	FileManifest      = "objects.json"
)

// pickDelimiter chọn dấu kết thúc câu không xuất hiện trong các câu lệnh: thân routine/trigger chứa ';'.
func pickDelimiter(stmts []string) string {
	for _, d := range []string{";;", "$$", "//", "%%", "@@"} {
		ok := true
		for _, s := range stmts {
			if strings.Contains(s, d) {
				ok = false
				break
			}
		}
		if ok {
			return d
		}
	}
	return ";;"
}

type fileEntry struct {
	comments []string
	stmt     string
}

type fileBuilder struct {
	stmts []string
	raw   []fileEntry
}

func (f *fileBuilder) add(comments []string, stmt string) {
	f.raw = append(f.raw, fileEntry{comments, stmt})
	if stmt != "" {
		f.stmts = append(f.stmts, stmt)
	}
}

// render ghi tệp chạy được bằng `mysql < file`: một dòng DELIMITER ở đầu, mỗi câu kết thúc bằng dấu đó.
func (f *fileBuilder) render(header []string) string {
	d := pickDelimiter(f.stmts)
	var sb strings.Builder
	for _, h := range header {
		sb.WriteString("-- " + h + "\n")
	}
	sb.WriteString("DELIMITER " + d + "\n\n")
	for _, r := range f.raw {
		for _, c := range r.comments {
			for _, line := range strings.Split(c, "\n") {
				sb.WriteString("-- " + line + "\n")
			}
		}
		if r.stmt != "" {
			sb.WriteString(r.stmt + "\n" + d + "\n")
		}
		sb.WriteString("\n")
	}
	sb.WriteString("DELIMITER ;\n")
	return sb.String()
}

func objComments(o Object) []string {
	c := []string{o.Label()}
	for _, w := range o.Warnings {
		c = append(c, "WARNING: "+w)
	}
	if o.SQLMode != "" {
		c = append(c, "source sql_mode (kept by `strand objects apply`; set it yourself before running this file by hand): "+o.SQLMode)
	}
	if o.TimeZone != "" {
		c = append(c, "event time_zone on the source: "+o.TimeZone+" (run SET time_zone first)")
	}
	return c
}

// Export ghi các tệp SQL và manifest vào dir.
func Export(set *Set, dir string, withUsers bool) ([]string, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	var written []string
	write := func(name, content string, mode os.FileMode) error {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(content), mode); err != nil {
			return err
		}
		written = append(written, p)
		return nil
	}
	addObj := func(f *fileBuilder, o Object) {
		if o.Skipped != "" {
			f.add(append(objComments(o), "SKIPPED: "+o.Skipped), "")
			return
		}
		f.add(objComments(o), o.Stmt)
	}
	hdr := func(extra ...string) []string {
		return append([]string{"Generated by `strand objects export`. Statements end with the DELIMITER below so `mysql < file` runs them as is."}, extra...)
	}

	var a fileBuilder
	for _, o := range set.Of(KindView, KindProcedure, KindFunction, KindPackage) {
		addObj(&a, o)
	}
	if err := write(FileViewsRoutines, a.render(hdr("Views (dependency order), procedures, functions. Run after the tables exist; safe while sync is running.")), 0o644); err != nil {
		return written, err
	}
	var e fileBuilder
	for _, o := range set.Of(KindEvent) {
		addObj(&e, o)
	}
	if err := write(FileEventsOff, e.render(hdr("Events created DISABLED: they must not run on the target before cutover.")), 0o644); err != nil {
		return written, err
	}
	var t fileBuilder
	for _, o := range set.Of(KindTrigger) {
		addObj(&t, o)
	}
	if err := write(FileTriggers, t.render(hdr("Triggers: create ONLY at cutover (after catch-up, before opening writes).",
		"The row-based binlog already holds the rows the source triggers wrote; a trigger on the target while syncing would apply them twice.")), 0o644); err != nil {
		return written, err
	}
	var en fileBuilder
	for _, o := range set.Of(KindEvent) {
		if o.Skipped == "" && o.EnableStmt != "" {
			en.add([]string{o.Label()}, o.EnableStmt)
		}
	}
	if err := write(FileEventsOn, en.render(hdr("Enable events at cutover, together with the triggers. The target also needs event_scheduler=ON.")), 0o644); err != nil {
		return written, err
	}
	if withUsers && set.Users != nil {
		var u fileBuilder
		for _, it := range set.Users.Items {
			var cm []string
			cm = append(cm, it.Account)
			for _, n := range it.Notes {
				cm = append(cm, "NOTE: "+n)
			}
			u.add(cm, "")
			for _, s := range it.Stmts {
				u.add(nil, s)
			}
		}
		for _, s := range set.Users.Skipped {
			u.add([]string{"skipped " + s}, "")
		}
		h := hdr("Users, roles and grants on the migrated schemas. Run after `--phase pre` (grants on routines/views need them).",
			"!!! Password hashes are mysql_native_password. MySQL 8.4 ships with that plugin DISABLED: start the target with mysql_native_password=ON,",
			"!!! or export with --auth reset (random caching_sha2_password passwords, printed in the NOTE lines) and give the new passwords to the applications.",
			"This file contains password hashes: keep it private.")
		if err := write(FileUsers, u.render(h), 0o600); err != nil {
			return written, err
		}
	}
	b, err := json.MarshalIndent(set, "", "  ")
	if err != nil {
		return written, err
	}
	if err := write(FileManifest, string(b)+"\n", 0o600); err != nil {
		return written, err
	}
	return written, nil
}

// LoadManifest đọc objects.json do Export ghi (dùng khi source không còn truy cập được).
func LoadManifest(dir string) (*Set, error) {
	b, err := os.ReadFile(filepath.Join(dir, FileManifest))
	if err != nil {
		return nil, fmt.Errorf("read objects manifest: %w", err)
	}
	var s Set
	if err := json.Unmarshal(b, &s); err != nil {
		return nil, fmt.Errorf("parse %s: %w", FileManifest, err)
	}
	return &s, nil
}
