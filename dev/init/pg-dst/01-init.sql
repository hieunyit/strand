-- spec: S03 §2 Quyền DB tối thiểu cho PostgreSQL target
CREATE ROLE strand WITH LOGIN PASSWORD 'dev';
CREATE SCHEMA IF NOT EXISTS app;
GRANT CONNECT, TEMPORARY ON DATABASE postgres TO strand;
GRANT USAGE, CREATE ON SCHEMA app TO strand;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app TO strand;
GRANT UPDATE ON ALL SEQUENCES IN SCHEMA app TO strand;
