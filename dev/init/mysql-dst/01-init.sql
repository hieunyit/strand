-- spec: S03 §2 Quyền DB tối thiểu cho MySQL target
CREATE USER IF NOT EXISTS 'strand'@'%' IDENTIFIED BY 'dev';
CREATE DATABASE IF NOT EXISTS app;
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, DROP ON app.* TO 'strand'@'%';
GRANT CONNECTION_ADMIN ON *.* TO 'strand'@'%';
FLUSH PRIVILEGES;
